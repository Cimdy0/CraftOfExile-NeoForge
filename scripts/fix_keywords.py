def main():
    with open(SRC, "r", encoding="utf-8") as f:
        data = json.load(f)

    assert isinstance(data, list), "root must be a list"
    out = []
    for entry in data:
        eid = entry["id"]
        if eid not in TR:
            raise SystemExit(f"missing translation for id={eid}")
        zh_title, zh_desc = TR[eid]
        new_entry = {
            "id": eid,
            "title": zh_title,
            "key": f"@coe:keyword.{eid}",
            "aliases": entry["aliases"],
            "description": zh_desc,
        }
        out.append(new_entry)

    # Validate
    assert len(out) == 49, f"expected 49 entries, got {len(out)}"
    seen = set()
    for e in out:
        assert e["id"] and e["title"], f"id/title missing: {e}"
        assert e["id"] not in seen, f"duplicate id: {e['id']}"
        seen.add(e["id"])
        assert isinstance(e["description"], list) and all(isinstance(d, str) for d in e["description"]), f"bad description: {e['id']}"
        assert e["key"] == f"@coe:keyword.{e['id']}", f"bad key: {e['id']}"

    with open(SRC, "w", encoding="utf-8", newline="") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")

    # re-read & verify
    with open(SRC, "r", encoding="utf-8") as f:
        verify = json.load(f)
    print(f"条目数: {len(verify)}")
    print(f"JSON 校验: 通过（数组、每条有 id+title、description 为字符串数组、key 存在）")
    print("样例:")
    for sample_id in ("ailment", "freeze", "resistance"):
        e = next(x for x in verify if x["id"] == sample_id)
        print(f"  [{sample_id}] title={e['title']} key={e['key']}")
        for line in e["description"]:
            print(f"      - {line}")


if __name__ == "__main__":
    main()
