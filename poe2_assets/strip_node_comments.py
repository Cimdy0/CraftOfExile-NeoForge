#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Strip all Java `//` line comments and `/* */` block comments from the 28 talent
node generation classes (keystone / notable / minor). String literals are respected,
so a `//` or `/*` that appears inside a "..." string literal is preserved.

The node classes are generated by gen_talent_stats.py, but that script only rewrites
the effects argument (TalentNodeDef.of(...) arg #6) and leaves all other lines — including
hand-written `//` comments above each node — untouched. This utility removes those comments
so the generated classes are comment-free (per request: "备注包括 Stat 文本也可以全部移除").

Usage:
  python strip_node_comments.py --dry     # list files whose comments would be removed
  python strip_node_comments.py --apply   # strip in place
"""
import os
import glob
import sys

NODEDIR = r"E:\McModding\Modding\CraftOfExile-NeoForge\src\main\java\com\cimdy\coe\data\gen\talent\node"
APPLY = "--apply" in sys.argv


def strip_line(line, in_block):
    """Return (stripped_line, still_in_block). Respects string literals."""
    if in_block:
        j = line.find("*/")
        if j < 0:
            return "", True
        line = line[j + 2:]
    res = []
    i = 0
    n = len(line)
    in_str = False
    esc = False
    while i < n:
        c = line[i]
        if in_str:
            res.append(c)
            if esc:
                esc = False
            elif c == '\\':
                esc = True
            elif c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            res.append(c)
            i += 1
            continue
        if c == '/' and i + 1 < n and line[i + 1] == '/':
            break  # line comment -> drop rest of line
        if c == '/' and i + 1 < n and line[i + 1] == '*':
            k = line.find("*/", i + 2)
            if k < 0:
                return "".join(res).rstrip(), True  # block open -> drop rest, stay in block
            line = line[k + 2:]
            n = len(line)
            i = 0
            continue
        res.append(c)
        i += 1
    return "".join(res).rstrip(), False


def strip_comments(text):
    out = []
    in_block = False
    for raw in text.split("\n"):
        stripped, in_block = strip_line(raw, in_block)
        out.append(stripped)
    return "\n".join(out)


def main():
    changed = 0
    for cat in ["keystone", "notable", "minor"]:
        for f in sorted(glob.glob(os.path.join(NODEDIR, cat, "*.java"))):
            if ".bak" in os.path.basename(f):
                continue
            src = open(f, encoding="utf-8", errors="replace").read()
            new = strip_comments(src)
            if new != src:
                if APPLY:
                    open(f, "w", encoding="utf-8", newline="\n").write(new)
                    print("STRIP  %s" % os.path.basename(f))
                else:
                    print("WOULD  %s" % os.path.basename(f))
                changed += 1
    print("TOTAL files with comments removed: %d  MODE: %s" % (changed, "APPLY" if APPLY else "DRY"))


if __name__ == "__main__":
    main()
